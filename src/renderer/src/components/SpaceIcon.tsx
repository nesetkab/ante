export function SpaceIcon({
  icon,
  size = 14,
  className,
}: {
  icon: string
  size?: number
  className?: string
}) {
  const symbol = symbolOf(icon)
  if (!symbol) return <span className={className}>{icon}</span>
  const Icon = symbols[symbol]
  return <Icon className={className} size={size} strokeWidth={2} aria-hidden />
}
